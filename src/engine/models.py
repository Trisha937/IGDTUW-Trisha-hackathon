"""
Data models for the AI/NLP Risk Engine outputs.
"""

from datetime import datetime, timezone
from typing import List, Optional
import uuid
from pydantic import BaseModel, Field

class RiskSignal(BaseModel):
    """
    Structured machine-readable risk signal generated by the AI/NLP engine.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    ticker: str = Field(..., description="Target stock ticker from Nifty 10 (e.g., 'INFY', 'RELIANCE')")
    sentiment_score: float = Field(..., ge=-1.0, le=1.0, description="Sentiment score from -1.0 (bearish) to +1.0 (bullish)")
    event_classification: str = Field(..., description="Category label from EVENT_TAXONOMY")
    impact_score: int = Field(..., ge=1, le=10, description="Severity score 1-10 (1-3 minor, 4-6 material, 7-8 major, 9-10 systemic)")
    confidence: float = Field(default=0.85, ge=0.0, le=1.0, description="Model confidence score")
    reason: str = Field(..., description="Concise explanation grounded in evidence")
    evidence_ids: List[str] = Field(default_factory=list, description="IDs of source raw items or memory records")
    source: str = Field(default="news", description="Source stream ('news', 'social', 'announcement')")
    model_version: str = Field(default="nemotron-3.5-v1", description="Model name or engine version")
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class AnalysisBatch(BaseModel):
    """Batch of risk signals produced across a stream or scenario."""
    batch_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    signals: List[RiskSignal]
    total_items_analyzed: int
    unresolved_count: int = 0
